"""内置模板（AGENT.md / 示例任务）的定位与读取。

源码运行时在包目录内；PyInstaller 冻结后由 entry_web 把路径指到 _MEIPASS。
所有内置文案的唯一来源都在 templates/ 目录，代码里不再维护副本；
模板读不到直接抛错（打包遗漏会立刻暴露，而不是静默生成残缺内容）。
"""

from __future__ import annotations

import re
from pathlib import Path

TEMPLATES_DIR = Path(__file__).parent / "templates"


def load_text(name: str) -> str:
    """读取内置模板全文；读不到或为空直接抛 RuntimeError，不做兜底。"""
    path = TEMPLATES_DIR / name
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        raise RuntimeError(f"内置模板读取失败：{path}（{e}）") from e
    if not text.strip():
        raise RuntimeError(f"内置模板为空：{path}")
    return text


def default_guide(project_name: str, project_path: Path | None = None,
                  overrides: dict[str, str] | None = None) -> str:
    """生成新项目/导入项目的 AGENT.md 初始内容。

    唯一来源是 templates/AGENT.md，只做两处替换：标题换成项目名、首行
    引言换成生成说明。web 新建项目落盘与 agent 缺指引时的兜底都走这里，
    保证同一份文案。

    Project 节的 Stack/Run/Test 占位填充优先级：
      overrides（用户在看板里填的）> 自动探测（project_path 给定时）> 留空。
    """
    text = load_text("AGENT.md")
    text = re.sub(r"^# .*$", f"# {project_name} — Development Guide",
                  text, count=1, flags=re.MULTILINE)
    text = re.sub(r"^> Place this file at the managed project root.*$",
                  "> Generated by task-arranger. The Agent reads this file before "
                  "every task; edit freely to fit this repo.",
                  text, count=1, flags=re.MULTILINE)
    probed: dict[str, str] = {}
    if overrides is None and project_path is not None:
        from .probe import probe_project
        probed = probe_project(project_path)
    values = overrides if overrides is not None else probed
    for field, placeholder in (("stack", "- Stack:"), ("run", "- Run:"),
                               ("test", "- Test:")):
        value = (values.get(field) or "").strip()
        if value:
            text = text.replace(placeholder, f"{placeholder} {value}", 1)
    return text
